#!/usr/bin/env python3
"""Trim, fade and peak-normalise chosen SFX into the project, and record their peak times.

usage: python3 sfx_prepare.py <selection.json> <project>/public/sfx [--ts <project>/src/sfxPeaks.ts] [--peak-db -1]

selection.json: { "whoosh_short_a": {"src": "/abs/path/Deep, Mini, Whoosh (1).wav", "max": 1.0, "lead": 0},
                  "click_c": {"src": "...", "max": 0.5, "lead": 0.18} }
- lead: seconds trimmed from the start (when a file has dead air before the transient)
- max:  seconds kept (tail faded over the last 0.12 s)
Peak time is measured on the processed file (RMS, 20 ms windows) and written to peaks.json
(and to a TypeScript module with --ts) so cue sheets can land peaks on cut frames.
"""
import argparse
import json
import os
import re
import subprocess
import numpy as np


def peak_time(path):
    raw = subprocess.run(["ffmpeg", "-v", "error", "-i", path, "-ac", "1", "-ar", "8000", "-f", "f32le", "-"], capture_output=True).stdout
    x = np.frombuffer(raw, dtype=np.float32)
    win = 160
    n = len(x) // win
    if n == 0:
        return 0.0
    rms = np.sqrt(np.mean(x[: n * win].reshape(n, win) ** 2, axis=1))
    return round((int(np.argmax(rms)) + 0.5) * 0.02, 3)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("selection")
    ap.add_argument("out_dir")
    ap.add_argument("--ts")
    ap.add_argument("--peak-db", type=float, default=-1.0)
    o = ap.parse_args()
    sel = json.load(open(o.selection))
    os.makedirs(o.out_dir, exist_ok=True)
    peaks = {}
    for name, spec in sel.items():
        src = spec["src"]
        lead = float(spec.get("lead", 0))
        mx = float(spec.get("max", 2.0))
        info = subprocess.run(
            ["ffmpeg", "-hide_banner", "-ss", str(lead), "-t", str(mx), "-i", src, "-af", "volumedetect", "-f", "null", "-"],
            capture_output=True, text=True,
        ).stderr
        m = re.search(r"max_volume: (-?[0-9.]+) dB", info)
        if not m:
            print(f"skip {name}: cannot read {src}")
            continue
        gain = o.peak_db - float(m.group(1))
        fo = max(0.05, mx - 0.12)
        dst = os.path.join(o.out_dir, f"{name}.wav")
        subprocess.run(
            ["ffmpeg", "-hide_banner", "-v", "error", "-y", "-ss", str(lead), "-t", str(mx), "-i", src,
             "-af", f"volume={gain:.2f}dB,afade=t=out:st={fo:.2f}:d=0.12", "-ar", "48000", "-ac", "2", "-c:a", "pcm_s16le", dst],
            check=True,
        )
        peaks[name] = peak_time(dst)
        print(f"{name:22s} gain {gain:+.1f} dB  peak {peaks[name]:.2f}s")
    json.dump(peaks, open(os.path.join(o.out_dir, "peaks.json"), "w"), indent=2)
    if o.ts:
        with open(o.ts, "w") as f:
            f.write("// Generated by scripts/sfx_prepare.py — peak offset (seconds) of each prepared SFX file.\n")
            f.write("export const SFX_PEAKS: Record<string, number> = ")
            f.write(json.dumps(peaks, indent=2))
            f.write(";\n")
        print("wrote", o.ts)


if __name__ == "__main__":
    main()
